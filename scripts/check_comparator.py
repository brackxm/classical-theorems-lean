#!/usr/bin/env python3
"""Keep comparator coverage complete; generate wrappers, never challenge statements."""
import argparse
import json
import re
from pathlib import Path

from check_imports import code_without_comments

ROOT = Path(__file__).resolve().parent.parent
AXIOMS = ['propext', 'Classical.choice', 'Quot.sound']
NAME = r'[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*'
DECLARATION = re.compile(rf'^theorem (Comparator\.({NAME}))(?:\.\{{([^}}]+)\}})?\s', re.M)
SOLUTION_HEADER = '''/-
Copyright 2026 Michael Brackx
SPDX-License-Identifier: Apache-2.0
-/

import ClassicalTheorems

/-! Generated by `scripts/check_comparator.py --write`.
Each wrapper uses the actual theorem's type, independently of the challenge statement. -/

'''


def check(root=ROOT, write=False):
    challenge = code_without_comments((root/'Comparator/Challenge.lean').read_text())
    declarations = list(DECLARATION.finditer(challenge))
    if not declarations:
        raise ValueError('Comparator challenge has no theorem statements')
    if len(re.findall(r'^theorem\b', challenge, re.M)) != len(declarations):
        raise ValueError('Every challenge theorem must use the Comparator prefix')
    # Keep this deliberately small statement file explicit: imports, opens and theorems only.
    preamble = challenge[:declarations[0].start()]
    if any(line.strip() and not line.startswith(('import ', 'open '))
           for line in preamble.splitlines()):
        raise ValueError('Challenge preamble may contain only imports and opens')
    if re.search(r'\b(?:axiom|def|abbrev|opaque|instance|structure|class|inductive|lemma|example)\b',
                 challenge):
        raise ValueError('Challenge must declare only independently stated theorems')
    wrappers, originals, solution, statements = [], [], [], []
    for i, match in enumerate(declarations):
        name, original, universes = match.groups()
        stop = declarations[i+1].start() if i+1 < len(declarations) else len(challenge)
        statement, separator, proof = challenge[match.end():stop].rpartition(':=')
        if not separator or proof.strip() != 'sorry' or 'type_of%' in statement:
            raise ValueError(f'{name}: challenge must state a type and use only `sorry`')
        wrappers.append(name)
        originals.append(original)
        statements.append(statement)
        levels = f'.{{{universes}}}' if universes else ''
        target = f'@_root_.{original}{levels}'
        solution.append(f'theorem {name}{levels} : type_of% {target} := {target}\n')
    if len(set(wrappers)) != len(wrappers):
        raise ValueError('Duplicate challenge theorem')
    audit = re.findall(rf'^#check_indexed ({NAME})\s*$', code_without_comments(
        (root/'ClassicalTheorems/IndexAudit.lean').read_text()), re.M)
    documented = re.findall(rf'\[`({NAME})`\]\(', (root/'theorems.md').read_text())
    if (sorted(originals) != sorted(audit) or sorted(originals) != sorted(documented)):
        raise ValueError('Challenge, IndexAudit and documented theorem lists must agree exactly')
    for original in originals:
        if re.search(rf'(?<![\w.]){re.escape(original)}(?![\w.])',
                     '\n'.join(statements)):
            raise ValueError('Challenge statements must not refer to the indexed proofs')
    expected = {
        'Comparator/Solution.lean': SOLUTION_HEADER + '\n'.join(solution),
        'comparator.json': json.dumps({
            'challenge_module': 'Comparator.Challenge',
            'solution_module': 'Comparator.Solution',
            'theorem_names': wrappers,
            'permitted_axioms': AXIOMS,
        }, indent=2) + '\n',
    }
    for relative, text in expected.items():
        path = root/relative
        if write:
            path.write_text(text)
        elif not path.is_file() or path.read_text() != text:
            raise ValueError(f'{relative} is stale; run python3 scripts/check_comparator.py --write')
    return len(wrappers)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate solution and configuration')
    args = parser.parse_args()
    count = check(write=args.write)
    print(f'Checked {count} comparator statements against the audit and documentation indexes.')


if __name__ == '__main__':
    main()
